<?php
namespace MDcart\System\Library\Extension\IranianGateways;
/**
 * Class Digipay
 *
 * Minimal client for DigiPay's UPG (Unified Payment Gateway) REST API, per
 * DigiPay's own integration documentation. Covers the pieces this store
 * actually needs: login (OAuth2 "password" grant), creating a purchase
 * ticket (type=11, no preferredGateway restriction, so the customer sees
 * whichever payment instruments - IPG, Wallet, BNPL/Credit - the merchant
 * account has enabled on DigiPay's own hosted page), verifying a completed
 * payment, and delivering a credit/BNPL purchase (the step DigiPay requires
 * once the goods have actually been handed over, for those two payment
 * types only). Refund/reverse/refund-inquiry are intentionally NOT
 * implemented here - no other gateway in this store has admin-triggered
 * refund actions either, so this follows the same scope.
 *
 * No token caching: a fresh login() is done for every ticket/verify/deliver
 * call. Simpler and safer than caching, and matches every other gateway in
 * this codebase (none of which persist any gateway-side session state) -
 * for this store's order volume, one extra login call per purchase/action
 * is not a real cost.
 *
 * @package MDcart\System\Library\Extension\IranianGateways
 */
class Digipay {
	private const BASE_URL = 'https://api.mydigipay.com/digipay/api';
	private const BASE_URL_SANDBOX = 'https://uat.mydigipay.info/digipay/api';

	// Literal value used in every one of DigiPay's own documented curl
	// examples for the Digipay-Version header - the documentation's prose
	// elsewhere describes a different (day-month-year) format for this same
	// field, but the actual worked examples consistently use this value, so
	// that's what's trusted here.
	private const API_VERSION = '2022-02-02';

	private string $client_id;
	private string $client_secret;
	private string $username;
	private string $password;
	private bool $sandbox;

	/**
	 * The most recent error message, in English (not shown to customers -
	 * used for admin-facing history comments and sandbox diagnostics only).
	 *
	 * @var string|null
	 */
	public ?string $error = null;

	public function __construct(string $client_id, string $client_secret, string $username, string $password, bool $sandbox = false) {
		$this->client_id = $client_id;
		$this->client_secret = $client_secret;
		$this->username = $username;
		$this->password = $password;
		$this->sandbox = $sandbox;
	}

	/**
	 * Log in and return a bearer access token, or null on failure (see
	 * $this->error).
	 *
	 * @return string|null
	 */
	public function login(): ?string {
		$this->error = null;

		$curl = curl_init($this->baseUrl() . '/oauth/token');

		curl_setopt($curl, CURLOPT_POST, true);
		// Sent as multipart/form-data (per DigiPay's documented curl
		// --form examples) - PHP's curl extension does this automatically
		// when CURLOPT_POSTFIELDS is given as an array rather than a string.
		curl_setopt($curl, CURLOPT_POSTFIELDS, [
			'username'   => $this->username,
			'password'   => $this->password,
			'grant_type' => 'password'
		]);
		curl_setopt($curl, CURLOPT_HTTPHEADER, [
			'Authorization: Basic ' . base64_encode($this->client_id . ':' . $this->client_secret)
		]);
		curl_setopt($curl, CURLOPT_RETURNTRANSFER, true);
		curl_setopt($curl, CURLOPT_SSL_VERIFYPEER, true);
		curl_setopt($curl, CURLOPT_CONNECTTIMEOUT, 15);
		curl_setopt($curl, CURLOPT_TIMEOUT, 30);

		$response = curl_exec($curl);
		$curl_error = curl_error($curl);

		curl_close($curl);

		if ($response === false) {
			$this->error = 'curl_error: ' . $curl_error;

			return null;
		}

		$result = json_decode((string)$response, true);

		if (!is_array($result) || empty($result['access_token'])) {
			$this->error = 'login_failed: ' . substr((string)$response, 0, 300);

			return null;
		}

		return (string)$result['access_token'];
	}

	/**
	 * Create a purchase ticket. On success, returns ['redirect_url' =>
	 * string, 'ticket' => string]; on failure, returns ['error' => string]
	 * (a message safe to show the customer is not derivable from DigiPay's
	 * response, so the caller should show its own generic error text and
	 * use $this->error / the returned raw message for diagnostics only).
	 *
	 * @param string $token
	 * @param string $cell_number
	 * @param int    $amount       Rial
	 * @param string $provider_id  A unique id generated by the caller for this purchase attempt
	 * @param string $callback_url
	 *
	 * @return array<string, string>
	 */
	public function createTicket(string $token, string $cell_number, int $amount, string $provider_id, string $callback_url): array {
		[$result, $error] = $this->request('POST', '/tickets/business?type=11', $token, [
			'cellNumber'  => $cell_number,
			'amount'      => $amount,
			'providerId'  => $provider_id,
			'callbackUrl' => $callback_url
		]);

		if ($error || !is_array($result)) {
			$this->error = 'ticket_request_failed: ' . $this->error;

			return ['error' => $this->error];
		}

		$status = $result['result']['status'] ?? null;

		if ($status !== 0 || empty($result['redirectUrl'])) {
			$this->error = 'ticket_rejected: status=' . var_export($status, true) . ';message=' . ($result['result']['message'] ?? '');

			return ['error' => $this->error];
		}

		return [
			'redirect_url' => (string)$result['redirectUrl'],
			'ticket'       => (string)($result['ticket'] ?? '')
		];
	}

	/**
	 * Verify a completed purchase. On success, returns ['success' => true,
	 * 'amount' => int]. On failure, ['success' => false] (see $this->error).
	 *
	 * @param string $token
	 * @param string $tracking_code
	 * @param string $provider_id
	 * @param int    $type
	 *
	 * @return array{success: bool, amount?: int}
	 */
	public function verify(string $token, string $tracking_code, string $provider_id, int $type): array {
		[$result, $error] = $this->request('POST', '/purchases/verify?type=' . $type, $token, [
			'trackingCode' => $tracking_code,
			'providerId'   => $provider_id
		]);

		if ($error || !is_array($result)) {
			$this->error = 'verify_request_failed: ' . $this->error;

			return ['success' => false];
		}

		$status = $result['result']['status'] ?? null;

		if ($status !== 0) {
			$this->error = 'verify_rejected: status=' . var_export($status, true) . ';message=' . ($result['result']['message'] ?? '');

			return ['success' => false];
		}

		return [
			'success' => true,
			'amount'  => (int)($result['amount'] ?? 0)
		];
	}

	/**
	 * Report a credit/BNPL purchase as delivered (required by DigiPay only
	 * for those two payment types - see the class docblock).
	 *
	 * @param string        $token
	 * @param string        $tracking_code
	 * @param int            $type
	 * @param string        $invoice_number
	 * @param array<string> $products
	 * @param int            $delivery_date_ms Epoch milliseconds
	 *
	 * @return bool
	 */
	public function deliver(string $token, string $tracking_code, int $type, string $invoice_number, array $products, int $delivery_date_ms): bool {
		[$result, $error] = $this->request('POST', '/purchases/deliver?type=' . $type, $token, [
			'deliveryDate'   => $delivery_date_ms,
			'invoiceNumber'  => $invoice_number,
			'trackingCode'   => $tracking_code,
			'products'       => $products ?: [$invoice_number]
		]);

		if ($error || !is_array($result)) {
			$this->error = 'deliver_request_failed: ' . $this->error;

			return false;
		}

		$status = $result['result']['status'] ?? null;

		if ($status !== 0) {
			$this->error = 'deliver_rejected: status=' . var_export($status, true) . ';message=' . ($result['result']['message'] ?? '');

			return false;
		}

		return true;
	}

	/**
	 * @return string
	 */
	private function baseUrl(): string {
		return $this->sandbox ? self::BASE_URL_SANDBOX : self::BASE_URL;
	}

	/**
	 * POST a JSON body to a DigiPay endpoint with the standard headers.
	 *
	 * @param string               $method Always POST for the endpoints used here, kept for clarity
	 * @param string               $path   Starting with "/", may include a query string
	 * @param string               $token  Bearer token
	 * @param array<string, mixed> $body
	 *
	 * @return array{0: mixed, 1: bool}
	 */
	private function request(string $method, string $path, string $token, array $body): array {
		$this->error = null;

		$curl = curl_init($this->baseUrl() . $path);

		curl_setopt($curl, CURLOPT_CUSTOMREQUEST, $method);
		curl_setopt($curl, CURLOPT_POSTFIELDS, json_encode($body));
		curl_setopt($curl, CURLOPT_HTTPHEADER, [
			'Authorization: Bearer ' . $token,
			'Content-Type: application/json',
			'Agent: WEB',
			'Digipay-Version: ' . self::API_VERSION
		]);
		curl_setopt($curl, CURLOPT_RETURNTRANSFER, true);
		curl_setopt($curl, CURLOPT_SSL_VERIFYPEER, true);
		curl_setopt($curl, CURLOPT_CONNECTTIMEOUT, 15);
		curl_setopt($curl, CURLOPT_TIMEOUT, 30);

		$response = curl_exec($curl);
		$curl_error = curl_error($curl);

		curl_close($curl);

		if ($response === false) {
			$this->error = 'curl_error: ' . $curl_error;

			return [null, true];
		}

		$result = json_decode((string)$response, true);

		if (!is_array($result)) {
			$this->error = 'invalid_json: ' . substr((string)$response, 0, 300);

			return [null, true];
		}

		return [$result, false];
	}
}
